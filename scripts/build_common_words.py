"""Generate services/orchestrator/app/word_df.tsv (+ common_words.txt) for burst/outage detection.

Words that appear in >= MIN_DF of KB tickets (e.g. "data" 30%, "system" 15%, "medical" 11%) are too
generic to show that several tickets describe the SAME failure, so burst detection ignores them.
Built from data/kb_train.csv only (never the holdout).

    python scripts/build_common_words.py [--min-df 0.015]
"""
import argparse
import collections
import os
import sys

import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "services", "orchestrator"))
sys.path.insert(0, os.path.join(ROOT, "shared"))
from app.burst import _STOP, _WORD  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument("--min-df", type=float, default=0.015)
a = ap.parse_args()
kb = pd.read_csv(os.path.join(ROOT, "data", "kb_train.csv"))
df: collections.Counter = collections.Counter()
for s, b in zip(kb["subject"].fillna(""), kb["body"].fillna("")):
    df.update({w.lower() for w in _WORD.findall(f"{s} {b}")})
words = sorted(w for w, c in df.items() if c / len(kb) >= a.min_df and w not in _STOP)
# Document frequency of every word seen in >= 3 KB tickets: burst.py weights shared words by rarity.
dfo = os.path.join(ROOT, "services", "orchestrator", "app", "word_df.tsv")
with open(dfo, "w", encoding="utf-8") as f:
    f.write(f"#n_docs\t{len(kb)}\n")
    for w, c in sorted(df.items()):
        if c >= 3 and w not in _STOP:
            f.write(f"{w}\t{c}\n")
out = os.path.join(ROOT, "services", "orchestrator", "app", "common_words.txt")
with open(out, "w", encoding="utf-8") as f:
    f.write(f"# generated by scripts/build_common_words.py --min-df {a.min_df} from data/kb_train.csv ({len(kb)} tickets)\n")
    f.write("\n".join(words) + "\n")
print(f"wrote {len(words)} common words to {out}")
